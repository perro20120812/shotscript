/** 提取模板中的占位符列表（去重保序） */
function extractPlaceholders(template) {
  const set = [];
  const re = /\{([^}]+)\}/g;
  let m;
  while ((m = re.exec(template)) !== null) {
    if (!set.includes(m[1])) set.push(m[1]);
  }
  return set;
}

/** 把模板正文中的占位符渲染成高亮片段（HTML） */
function renderTemplateBody(body) {
  return body.replace(/\{([^}]+)\}/g, '<span class="placeholder-chip">{<wbr>$1}</span>');
}

/** 用值字典替换占位符生成成稿 */
function fillTemplate(body, values) {
  return body.replace(/\{([^}]+)\}/g, (_, key) => {
    const v = (values[key] || '').trim();
    return v || '{' + key + '}';
  });
}
